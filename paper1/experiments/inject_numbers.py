"""
Generate paper1/paper/numbers.tex — LaTeX macros for every result number —
from paper1/experiments/results/*.json. main.tex \\input{numbers} so the paper
always reflects the latest sweep without hand-copying.

Macro naming: \\cer<Run>, \\aer<Run>, \\wacc<Run>, \\params<Run>
where <Run> is the run name in CamelCase (lora_r16_attn -> LoraRSixteenAttn is
unwieldy; we use short aliases below instead).

Usage:
    python -m paper1.experiments.inject_numbers
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS_DIR = Path(__file__).resolve().parent / "results"
OUTPUT = Path(__file__).resolve().parents[2] / "paper1" / "paper" / "numbers.tex"

# run_name -> LaTeX-safe alias
ALIASES = {
    "base_prep": "BasePrep",
    "lora_r4_attn": "LoraFourAttn",
    "lora_r8_attn": "LoraEightAttn",
    "lora_r16_attn": "LoraSixteenAttn",
    "lora_r32_attn": "LoraThirtytwoAttn",
    "lora_r16_attn_ffn": "LoraSixteenAttnFfn",
    "lora_r16_legacy": "LoraSixteenLegacy",
    "full_ft": "FullFt",
    "lora_r16_attn_synth25": "SynthTwoFive",   # +2.5% of real train size
    "lora_r16_attn_synth50": "SynthFive",      # +5%
    "lora_r16_attn_synth100": "SynthTen",      # +10%
    # archived raw-pipeline baseline for the preprocessing ablation
    "raw_pipeline_archive/base_checkpoint_m16": "BaseRaw",
}


def fmt_params(count) -> str:
    return "---" if count is None else f"{count / 1e6:.2f}M"


def main() -> None:
    lines = ["% Auto-generated by paper1/experiments/inject_numbers.py — do not edit."]
    found = 0
    for run_name, alias in ALIASES.items():
        path = RESULTS_DIR / f"{run_name}.json"
        if not path.exists():
            lines.append(f"% {run_name}: no results yet")
            for prefix in ("cer", "aer", "wacc", "cerlo", "cerhi", "params"):
                lines.append(f"\\newcommand{{\\{prefix}{alias}}}{{--}}")
            continue
        with path.open("r", encoding="utf-8") as fh:
            s = json.load(fh)["summary"]
        lines.append(f"% {run_name} (n={s['num_samples']})")
        lines.append(f"\\newcommand{{\\cer{alias}}}{{{s['cer']:.4f}}}")
        lines.append(f"\\newcommand{{\\aer{alias}}}{{{s['aer']:.4f}}}")
        lines.append(f"\\newcommand{{\\wacc{alias}}}{{{s['word_accuracy']:.4f}}}")
        lines.append(f"\\newcommand{{\\cerlo{alias}}}{{{s['cer_ci95'][0]:.4f}}}")
        lines.append(f"\\newcommand{{\\cerhi{alias}}}{{{s['cer_ci95'][1]:.4f}}}")
        lines.append(f"\\newcommand{{\\params{alias}}}{{{fmt_params(s.get('trainable_params'))}}}")
        found += 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[inject_numbers] {found}/{len(ALIASES)} runs available -> {OUTPUT}")


if __name__ == "__main__":
    main()
